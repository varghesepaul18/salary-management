CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number VARCHAR(20) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    country_code CHAR(2) NOT NULL,
    department VARCHAR(100) NOT NULL,
    employment_status VARCHAR(20) NOT NULL,
    CONSTRAINT chk_employee_country_code
        CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT chk_employee_status
        CHECK (employment_status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE salary_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    annual_base_salary NUMERIC(19, 4) NOT NULL,
    currency_code VARCHAR(3) NOT NULL,
    effective_from DATE NOT NULL,
    changed_by VARCHAR(100) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_salary_positive
        CHECK (annual_base_salary > 0),
    CONSTRAINT chk_salary_currency_code
        CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT uq_salary_employee_effective_date
        UNIQUE (employee_id, effective_from)
);

CREATE INDEX idx_employees_name
    ON employees (lower(last_name), lower(first_name));

CREATE INDEX idx_employees_country_department
    ON employees (country_code, department);

CREATE INDEX idx_salary_history_employee_effective_date
    ON salary_history (employee_id, effective_from DESC);